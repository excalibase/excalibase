func strPtr(s string) *string { return &s }

// --- RestoreRequest target project id ---

// The restore target id is generated by the platform. A body that names one
// must not reach the request: a caller who could pick it could point a restore
// at another tenant's project (EXC-415).
func TestRestoreRequestIgnoresACallerSuppliedProjectID(t *testing.T) {
	var r RestoreRequest
	body := `{"newProjectName":"` + testDTORestoredName + `","newProjectId":"` + testDTOProjID + `","targetProjectId":"` + testDTOProjID + `"}`
	if err := json.Unmarshal([]byte(body), &r); err != nil {
		t.Fatalf("decode: %v", err)
	}
	if r.TargetProjectID != "" {
		t.Errorf("target project id came from the request body: %q", r.TargetProjectID)
	}
	if r.NewProjectName != testDTORestoredName {
		t.Errorf("newProjectName: got %q, want %q", r.NewProjectName, testDTORestoredName)
	}
}

// A display name is the one piece of naming the caller owns, and it is required.
func TestRestoreRequestRequiresADisplayName(t *testing.T) {
	if err := (RestoreRequest{NewProjectName: testDTORestoredName}).Validate(); err != nil {
		t.Errorf("a named restore must validate: %v", err)
	}
	if err := (RestoreRequest{}).Validate(); err == nil {
		t.Error("a restore without newProjectName must be rejected")
	}
}

