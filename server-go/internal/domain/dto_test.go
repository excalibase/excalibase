	testDTOMarshalFmt   = "marshal: %v"
	testDTOUnmarshalFmt = "unmarshal: %v"
	testDTORestoredName = "my-restored-project"
	testDTOProjID       = "proj-id-123"
	testDTOGetNewFmt    = "GetNewProject: got %q, want %q"
	testDTONameWins     = "name-wins"
